a = int(input())

if a % 2 == 0:
    print('Число четное')
else:
    print('Число нечетное')

if a > 0:
    print('положительное')
elif a < 0:
    print('отрицательное')
else:
    print('ноль')
if 10 <= a <= 50:
    print('принадлежит диапазону [10, 50]')
else:
    print('не принадлежит диапазону [10, 50]')